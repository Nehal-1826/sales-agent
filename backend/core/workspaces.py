def provision_workspace(workspace):
    """Idempotently create the 4 default AgentConfig rows + the AppSettings
    row for `workspace`. Never overwrites rows that already exist."""
    with workspace_context(workspace):
        for agent, defaults in AGENT_DEFAULTS.items():
            AgentConfig.objects.get_or_create(agent=agent, defaults=defaults)
        # load() also absorbs env secrets, but only for the default tenant
        AppSettings.load()
    return workspace


class WorkspaceChoiceError(Exception):
    """The operator must pick a workspace (or the slug is unknown)."""


def resolve_workspace(slug=''):
    """Workspace for a one-off ops script. A slug is required as soon as more
    than one workspace exists, so a script never silently hits the wrong
    company's data."""
    if slug:
        ws = Workspace.all_tenants.filter(slug=slug.strip().lower()).first()
        if ws is None:
            raise WorkspaceChoiceError(f'No workspace with slug "{slug}".')
        return ws
    found = list(Workspace.all_tenants.order_by('id')[:2])
    if len(found) == 1:
        return found[0]
    if not found:
        raise WorkspaceChoiceError('No workspace exists yet.')
    raise WorkspaceChoiceError('Several workspaces exist: pass --workspace <slug>.')
