import { useState } from 'react';
import { AlertTriangle, X } from 'lucide-react';
import { cn } from '@/lib/cn';

interface DummyModeBannerProps {
  className?: string;
}

/**
 * Accent-tinted banner clarifying that the payments area is demo-only.
 * Dismissible via local state — re-appears on a full page reload.
 */
export function DummyModeBanner({ className }: DummyModeBannerProps) {
  const [dismissed, setDismissed] = useState(false);
  if (dismissed) return null;

  return (
    <div
      role="status"
      className={cn(
        'flex items-start gap-3 rounded-xl border border-accent4/30 bg-accent4/10 p-4 text-sm text-text',
        className,
      )}
    >
      <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-accent4" aria-hidden />
      <div className="min-w-0 flex-1">
        <p className="font-semibold text-accent4">Dummy payments — no real money moves.</p>
        <p className="mt-0.5 text-xs text-text-dim">
          Records shown here are generated by WarmPulse's internal billing fixture so you can
          exercise the admin dashboards without a live Stripe connection. All charges, refunds,
          and invoice IDs are synthetic.
        </p>
      </div>
      <button
        type="button"
        onClick={() => setDismissed(true)}
        className="shrink-0 rounded-md p-1 text-text-dim hover:bg-surface-2 hover:text-text focus-ring"
        aria-label="Dismiss demo-mode banner"
      >
        <X className="h-4 w-4" />
      </button>
    </div>
  );
}
