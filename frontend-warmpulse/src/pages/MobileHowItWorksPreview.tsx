            <g key={i}><line x1="50" y1="50" x2={x} y2={y} stroke={s.hex} strokeOpacity="0.25" strokeWidth="0.3" /><motion.circle r="0.9" fill={s.hex} animate={{ cx: [50, x, 50], cy: [50, y, 50], opacity: [0, 1, 0] }} transition={{ duration: 2, repeat: Infinity, delay: i * 0.32, ease: 'easeInOut' }} /></g>
